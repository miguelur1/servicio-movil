'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  listDevices: () => ipcRenderer.invoke('devices:list'),
  info: (platform, serial) => ipcRenderer.invoke('device:info', platform, serial),
  screenshot: (platform, serial) => ipcRenderer.invoke('device:screenshot', platform, serial),
  logs: (platform, serial) => ipcRenderer.invoke('device:logs', platform, serial),
  installApk: (serial) => ipcRenderer.invoke('android:install', serial),
  reboot: (serial, mode, fromFastboot) => ipcRenderer.invoke('android:reboot', serial, mode, fromFastboot),
  toolsStatus: () => ipcRenderer.invoke('tools:status'),
  version: () => ipcRenderer.invoke('app:version'),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  backup: (id, platform, serial, opts) => ipcRenderer.invoke('data:backup', id, platform, serial, opts),
  restore: (id, platform, serial) => ipcRenderer.invoke('data:restore', id, platform, serial),
  photos: (id, platform, serial, opts) => ipcRenderer.invoke('data:photos', id, platform, serial, opts),
  sendPhotos: (id, serial) => ipcRenderer.invoke('data:sendPhotos', id, serial),
  contacts: (id, platform, serial, opts) => ipcRenderer.invoke('data:contacts', id, platform, serial, opts),
  messages: (id, platform, serial, opts) => ipcRenderer.invoke('data:messages', id, platform, serial, opts),
  iosBackupInfo: (udid) => ipcRenderer.invoke('data:iosBackupInfo', udid),
  iosBrowse: (udid, text) => ipcRenderer.invoke('data:iosBrowse', udid, text),
  iosExtract: (udid, ids) => ipcRenderer.invoke('data:iosExtract', udid, ids),
  listFiles: (serial, dir) => ipcRenderer.invoke('files:list', serial, dir),
  pullFiles: (serial, remotes) => ipcRenderer.invoke('files:pull', serial, remotes),
  pushFiles: (serial, dir) => ipcRenderer.invoke('files:push', serial, dir),
  cancelJob: (id) => ipcRenderer.invoke('job:cancel', id),
  onProgress: (cb) => ipcRenderer.on('job:progress', (_e, p) => cb(p)),
  onUpdate: (cb) => ipcRenderer.on('update:status', (_e, s) => cb(s)),
});
