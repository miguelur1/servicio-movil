'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  listDevices: () => ipcRenderer.invoke('devices:list'),
  info: (platform, serial) => ipcRenderer.invoke('device:info', platform, serial),
  screenshot: (platform, serial) => ipcRenderer.invoke('device:screenshot', platform, serial),
  logs: (platform, serial) => ipcRenderer.invoke('device:logs', platform, serial),
  analyzeLogs: (platform, serial, text) => ipcRenderer.invoke('device:analyzeLogs', platform, serial, text),
  components: (platform, serial) => ipcRenderer.invoke('diag:components', platform, serial),
  diagTest: (serial, test, on) => ipcRenderer.invoke('diag:test', serial, test, on),
  factoryMenu: (manufacturer) => ipcRenderer.invoke('diag:factoryMenu', manufacturer),
  installApk: (serial) => ipcRenderer.invoke('android:install', serial),
  reboot: (serial, mode, fromFastboot) => ipcRenderer.invoke('android:reboot', serial, mode, fromFastboot),
  toolsStatus: () => ipcRenderer.invoke('tools:status'),
  battery: (platform, serial) => ipcRenderer.invoke('diag:battery', platform, serial),
  report: (platform, serial, extra) => ipcRenderer.invoke('diag:report', platform, serial, extra),
  reportOpen: (f) => ipcRenderer.invoke('report:open', f),
  reportShow: (f) => ipcRenderer.invoke('report:show', f),
  reportSaveAs: (f) => ipcRenderer.invoke('report:saveAs', f),
  reportCopy: (f) => ipcRenderer.invoke('report:copy', f),
  reportWhatsapp: (f) => ipcRenderer.invoke('report:whatsapp', f),
  reportEmail: (f, device) => ipcRenderer.invoke('report:email', f, device),
  reportToPhone: (f, platform, serial) => ipcRenderer.invoke('report:toPhone', f, platform, serial),
  appsList: (platform, serial, opts) => ipcRenderer.invoke('apps:list', platform, serial, opts),
  appsUninstall: (platform, serial, id, opts) => ipcRenderer.invoke('apps:uninstall', platform, serial, id, opts),
  appsSetEnabled: (serial, id, enabled) => ipcRenderer.invoke('apps:setEnabled', serial, id, enabled),
  appsRestoreSystem: (serial, id) => ipcRenderer.invoke('apps:restoreSystem', serial, id),
  appsBackup: (serial, ids) => ipcRenderer.invoke('apps:backup', serial, ids),
  appsInstall: (platform, serial) => ipcRenderer.invoke('apps:install', platform, serial),
  migratePlan: (from, to) => ipcRenderer.invoke('migrate:plan', from, to),
  migrate: (id, src, dst, opts) => ipcRenderer.invoke('migrate:run', id, src, dst, opts),
  artPreview: (platform, serial) => ipcRenderer.invoke('art:preview', platform, serial),
  artPhoto: (name) => ipcRenderer.invoke('art:photo', name),
  artSetPhoto: (name) => ipcRenderer.invoke('art:setPhoto', name),
  artRemovePhoto: (name) => ipcRenderer.invoke('art:removePhoto', name),
  artKind: (info) => ipcRenderer.invoke('art:kind', info),
  repairDevice: (name) => ipcRenderer.invoke('repair:device', name),
  repairGuide: (id) => ipcRenderer.invoke('repair:guide', id),
  repairLinks: (name) => ipcRenderer.invoke('repair:links', name),
  repairSearch: (name, es, en) => ipcRenderer.invoke('repair:search', name, es, en),
  settingsGet: () => ipcRenderer.invoke('settings:get'),
  settingsSet: (patch) => ipcRenderer.invoke('settings:set', patch),
  openUrl: (url) => ipcRenderer.invoke('open:url', url),
  libraryList: (name) => ipcRenderer.invoke('library:list', name),
  libraryAdd: (name) => ipcRenderer.invoke('library:add', name),
  libraryOpen: (name, file) => ipcRenderer.invoke('library:open', name, file),
  libraryFolder: (name) => ipcRenderer.invoke('library:folder', name),
  restartAdb: () => ipcRenderer.invoke('tools:restartAdb'),
  installGoogleDriver: () => ipcRenderer.invoke('drivers:google'),
  platform: () => ipcRenderer.invoke('app:platform'),
  version: () => ipcRenderer.invoke('app:version'),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  backup: (id, platform, serial, opts) => ipcRenderer.invoke('data:backup', id, platform, serial, opts),
  restore: (id, platform, serial) => ipcRenderer.invoke('data:restore', id, platform, serial),
  photos: (id, platform, serial, opts) => ipcRenderer.invoke('data:photos', id, platform, serial, opts),
  sendPhotos: (id, serial) => ipcRenderer.invoke('data:sendPhotos', id, serial),
  contacts: (id, platform, serial, opts) => ipcRenderer.invoke('data:contacts', id, platform, serial, opts),
  messages: (id, platform, serial, opts) => ipcRenderer.invoke('data:messages', id, platform, serial, opts),
  iosBackupInfo: (udid) => ipcRenderer.invoke('data:iosBackupInfo', udid),
  iosBrowse: (udid, text) => ipcRenderer.invoke('data:iosBrowse', udid, text),
  iosExtract: (udid, ids) => ipcRenderer.invoke('data:iosExtract', udid, ids),
  listFiles: (serial, dir) => ipcRenderer.invoke('files:list', serial, dir),
  pullFiles: (serial, remotes) => ipcRenderer.invoke('files:pull', serial, remotes),
  pushFiles: (serial, dir) => ipcRenderer.invoke('files:push', serial, dir),
  cancelJob: (id) => ipcRenderer.invoke('job:cancel', id),
  onProgress: (cb) => ipcRenderer.on('job:progress', (_e, p) => cb(p)),
  onUpdate: (cb) => ipcRenderer.on('update:status', (_e, s) => cb(s)),
});
